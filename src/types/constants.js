function normalizeName(s) {
  return s.toLowerCase().replace(/[^a-z0-9]/g, '');
}

export const syncVerifiedMembers = (membersList) => {
  const updatedList = [...membersList];
  const matchedIds = new Set();
  let maxId = 0;

  updatedList.forEach(m => {
    const idNum = parseInt(m.id.replace('mem-', ''), 10);
    if (!isNaN(idNum) && idNum > maxId) maxId = idNum;
  });

  VERIFIED_MEMBER_CONTACTS.forEach(v => {
    const vNorm = normalizeName(v.name);
    
    // Find existing member by normalized name
    let member = updatedList.find(m => !matchedIds.has(m.id) && normalizeName(m.fullName) === vNorm);

    // Aliases matching for slight spelling variations
    if (!member) {
      if (vNorm === 'siskurpa') member = updatedList.find(m => !matchedIds.has(m.id) && normalizeName(m.fullName) === 'siskrupa');
      if (vNorm === 'sisnandini') member = updatedList.find(m => !matchedIds.has(m.id) && normalizeName(m.fullName) === 'sisnandhini');
      if (vNorm === 'brophinehas') member = updatedList.find(m => !matchedIds.has(m.id) && normalizeName(m.fullName) === 'brophineas');
      if (vNorm === 'brosurendhran') member = updatedList.find(m => !matchedIds.has(m.id) && normalizeName(m.fullName) === 'brosurendran');
      if (vNorm === 'sisthilaka') member = updatedList.find(m => !matchedIds.has(m.id) && normalizeName(m.fullName) === 'sistilaka');
      if (vNorm === 'broabhishiek') member = updatedList.find(m => !matchedIds.has(m.id) && normalizeName(m.fullName) === 'broabhishek');
      if (vNorm === 'broebenezer') member = updatedList.find(m => !matchedIds.has(m.id) && normalizeName(m.fullName) === 'broebenezersham');
      if (vNorm === 'sisshilpa' && v.phone === '+91 6363267030') member = updatedList.find(m => !matchedIds.has(m.id) && normalizeName(m.fullName) === 'sisshilpashree');
      if (vNorm === 'broraju' && v.phone === '+91 9380928574') member = updatedList.find(m => !matchedIds.has(m.id) && normalizeName(m.fullName) === 'brorajumn');
    }

    if (member) {
      matchedIds.add(member.id);
      if (!member.userCustomized) {
        member.phone = v.phone;
        member.whatsappNumber = v.phone;
      }
    } else {
      // Create new member object
      maxId++;
      let formattedTitleName = v.name;
      if (v.name.startsWith('Bro ') || v.name.startsWith('Sis ') || v.name.startsWith('Pas ')) {
        formattedTitleName = v.name.replace(/^(Bro|Sis|Pas)\s/, '$1. ');
      }
      const newMember = {
        id: `mem-${maxId}`,
        fullName: formattedTitleName,
        phone: v.phone,
        whatsappNumber: v.phone,
        whatsappEnabled: true,
        whatsappOptIn: true,
        active: true,
        availability: 'Available',
        ministry: v.name.startsWith('Sis') ? 'Intercession & Prayer' : v.name.startsWith('Bro') ? 'General Ministry' : 'Pastoral & Preaching',
        notes: 'Verified Contact',
        lastAssignedDate: '2026-08-15',
        totalAssignments: 2,
        confirmedAssignments: 2,
        declinedAssignments: 0,
        completedAssignments: 2,
        missedAssignments: 0,
        participationHistory: []
      };
      updatedList.push(newMember);
      matchedIds.add(newMember.id);
    }
  });

  return updatedList;
};

